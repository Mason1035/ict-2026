def synthetic_payload(seq=1, **changes):
    # Wire fixture generated by V2Serializer from local Git object 08b2b14
    # using synthetic inputs. Mutations exercise distinct paths and rejections.
    payload = json.loads(FIXTURE.read_text())
    payload.update(seq=seq, uptime_ms=5000 + seq * 1000)
    payload.update(changes)
    return payload


def message(payload, topic=TOPIC):
    return SimpleNamespace(topic=topic, payload=json.dumps(payload).encode(), retain=False)


def count(db, table, where="1=1"):
    with db.connection() as connection:
        return connection.execute(f"SELECT count(*) FROM {table} WHERE {where}").fetchone()[0]


def assert_platform_db_has_zero_reserved_rows(platform_db):
    assert count(platform_db, "telemetry", f"device_id='{DEVICE}' OR site_id='{SITE}'") == 0
    assert count(platform_db, "alarms", f"device_id='{DEVICE}' OR site_id='{SITE}'") == 0
    assert count(platform_db, "events", f"device_id='{DEVICE}' OR site_id='{SITE}'") == 0
    assert count(platform_db, "boot_sessions", f"device_id='{DEVICE}'") == 0
    assert count(platform_db, "quarantine", f"topic='{TOPIC}' OR topic LIKE '%{DEVICE}%' OR topic LIKE '%{SITE}%'") == 0
    assert count(platform_db, "intake_receipts", f"topic='{TOPIC}' OR topic LIKE '%{DEVICE}%' OR topic LIKE '%{SITE}%'") == 0
    assert count(platform_db, "provisional_risk", f"telemetry_id IN (SELECT id FROM telemetry WHERE device_id='{DEVICE}' OR site_id='{SITE}')") == 0
    assert count(platform_db, "inference_results", f"device_id='{DEVICE}' OR site_id='{SITE}'") == 0
    with platform_db.connection() as connection:
        connectors = connection.execute("SELECT id, config_json FROM connectors").fetchall()
        reserved_ids = [
            row["id"] for row in connectors
            if SITE in row["config_json"] or DEVICE in row["config_json"]
        ]
        assert reserved_ids == []


